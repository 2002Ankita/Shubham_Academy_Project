from typing import Optional, Dict, Any
from app.models.student import Student
from app.models.teacher import Teacher
from app.models.fees import FeePayment
from app.models.salary import SalaryPayment
from app.models.passout_student import PassoutStudent
from app.models.user import User
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
import io
from datetime import datetime

async def generate_dashboard_report(current_user: User, branch_filter: Optional[str] = None) -> Dict[str, Any]:
    role_norm = (current_user.role or "").lower().replace("-", "_")
    
    # Determine branch scope
    target_branch = None
    if role_norm == "admin":
        target_branch = current_user.branch
    elif role_norm == "super_admin":
        if branch_filter and branch_filter.upper() not in ["ALL", "CONSOLIDATED"]:
            target_branch = branch_filter

    student_query = {}
    fee_query = {}
    teacher_query = {}
    salary_query = {}

    if target_branch:
        # Match case-insensitively
        regex_branch = {"$regex": f"^{target_branch}", "$options": "i"}
        student_query["branch"] = regex_branch
        fee_query["branch"] = regex_branch
        teacher_query["branch"] = regex_branch
        salary_query["branch"] = regex_branch

    total_students = await Student.find(student_query).count()
    total_teachers = await Teacher.find(teacher_query).count()
    total_passout = await PassoutStudent.count()
    
    # Fee statistics
    fee_payments = await FeePayment.find(fee_query).to_list()
    total_fees_collected = sum(float(p.amount_paid or 0) for p in fee_payments)
    
    # Salary statistics
    salary_payments = await SalaryPayment.find(salary_query).to_list()
    total_salary_disbursed = sum(float(s.amount or s.net_salary or 0) for s in salary_payments)

    return {
        "status": "Active",
        "institution": "Shubham Classes, Kolhapur",
        "scope": target_branch or "Both Campuses (Consolidated)",
        "authorized_role": current_user.role,
        "total_students": total_students,
        "total_teachers": total_teachers,
        "total_passout": total_passout,
        "total_fees_collected": total_fees_collected,
        "total_salary_disbursed": total_salary_disbursed,
        "fee_transactions_count": len(fee_payments),
        "salary_disbursements_count": len(salary_payments),
        "generated_at": datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    }

async def generate_excel_export(module: str, current_user: User, branch_filter: Optional[str] = None) -> bytes:
    role_norm = (current_user.role or "").lower().replace("-", "_")
    target_branch = None
    if role_norm == "admin":
        target_branch = current_user.branch
    elif role_norm == "super_admin" and branch_filter and branch_filter.upper() not in ["ALL", "CONSOLIDATED"]:
        target_branch = branch_filter

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = module.capitalize()[:31]

    # Color Palette - Deep Maroon & Gold Shubham Classes
    primary_color = "8B1216"
    accent_color = "FEF2F2"
    border_color = "E2E8F0"

    # Title Block
    ws.merge_cells("A1:G1")
    cell_a1 = ws["A1"]
    cell_a1.value = "SHUBHAM CLASSES - KOLHAPUR"
    cell_a1.font = Font(name="Calibri", size=16, bold=True, color="FFFFFF")
    cell_a1.fill = PatternFill(start_color=primary_color, end_color=primary_color, fill_type="solid")
    cell_a1.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 35

    ws.merge_cells("A2:G2")
    cell_a2 = ws["A2"]
    cell_a2.value = f"OFFICIAL ACADEMY AUDIT REPORT: {module.upper()} MODULE"
    cell_a2.font = Font(name="Calibri", size=11, bold=True, color="475569")
    cell_a2.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 22

    ws.merge_cells("A3:G3")
    cell_a3 = ws["A3"]
    scope_display = target_branch if target_branch else "All Campuses (Mangalvar Peth & Tarabai Park)"
    cell_a3.value = f"Campus Scope: {scope_display}  |  Generated by: {current_user.full_name} ({current_user.role})  |  Date: {datetime.now().strftime('%d %b %Y, %I:%M %p')}"
    cell_a3.font = Font(name="Calibri", size=9, italic=True, color="64748B")
    cell_a3.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[3].height = 18

    # Query matching data
    headers = []
    rows = []

    if module.lower() in ["students", "student"]:
        headers = ["Roll No", "Student Name", "Standard", "Academic Batch", "Branch Campus", "Parent Mobile", "Total Fees (₹)", "Paid (₹)", "Balance (₹)", "Status"]
        query = {}
        if target_branch:
            query["branch"] = {"$regex": f"^{target_branch}", "$options": "i"}
        students = await Student.find(query).to_list()
        for s in students:
            total_f = float(s.total_fees or 0)
            paid_f = float(s.paid_fees or 0)
            bal = max(0.0, total_f - paid_f)
            rows.append([
                s.roll_number or s.student_id or "N/A",
                s.name or "N/A",
                s.standard or "General",
                s.academic_batch or "Regular",
                s.branch or "Tarabai Park",
                s.parent_mobile or s.contact_number or "N/A",
                total_f,
                paid_f,
                bal,
                "Confirmed" if s.admission_confirmation_status == "CONFIRMED" else "Pending"
            ])

    elif module.lower() in ["fees", "fee"]:
        headers = ["Receipt ID", "Student Name", "Roll Number", "Campus Branch", "Amount Paid (₹)", "Payment Mode", "Date", "Fee Head", "Remarks"]
        query = {}
        if target_branch:
            query["branch"] = {"$regex": f"^{target_branch}", "$options": "i"}
        payments = await FeePayment.find(query).to_list()
        for p in payments:
            rows.append([
                p.transaction_reference or p.receipt_number or str(p.id),
                p.student_name or "Student",
                p.roll_number or "N/A",
                p.branch or "Kolhapur",
                float(p.amount_paid or 0),
                p.payment_method or "Counter",
                p.payment_date.strftime("%d-%m-%Y") if p.payment_date else "N/A",
                p.fee_category or "Tuition Fee",
                p.remarks or ""
            ])

    elif module.lower() in ["salary", "payroll"]:
        headers = ["Teacher Name", "Campus Branch", "Month", "Base Salary (₹)", "Working Hours", "Net Payable (₹)", "Payment Mode", "Status"]
        query = {}
        if target_branch:
            query["branch"] = {"$regex": f"^{target_branch}", "$options": "i"}
        salaries = await SalaryPayment.find(query).to_list()
        for s in salaries:
            rows.append([
                s.teacher_name or "Faculty",
                s.branch or "Kolhapur",
                s.month or "Current",
                float(s.base_salary or 0),
                float(s.working_hours or 0),
                float(s.amount or s.net_salary or 0),
                s.payment_mode or "NEFT",
                s.status or "Disbursed"
            ])

    else:
        headers = ["Record ID", "Module", "Description", "Campus Branch", "Status"]
        rows.append(["REC-01", module.capitalize(), f"General Report for {module}", target_branch or "Consolidated", "Active"])

    # Header Row in row 5
    header_fill = PatternFill(start_color="8B1216", end_color="8B1216", fill_type="solid")
    header_font = Font(name="Calibri", size=10, bold=True, color="FFFFFF")
    thin_border = Border(
        left=Side(style='thin', color=border_color),
        right=Side(style='thin', color=border_color),
        top=Side(style='thin', color=border_color),
        bottom=Side(style='thin', color=border_color)
    )

    ws.row_dimensions[5].height = 24
    for col_idx, h in enumerate(headers, 1):
        c = ws.cell(row=5, column=col_idx)
        c.value = h
        c.fill = header_fill
        c.font = header_font
        c.alignment = Alignment(horizontal="center", vertical="center")
        c.border = thin_border

    # Data Rows
    row_alt_fill = PatternFill(start_color="FFF9F9", end_color="FFF9F9", fill_type="solid")
    for r_idx, row_data in enumerate(rows, 6):
        ws.row_dimensions[r_idx].height = 20
        use_alt = (r_idx % 2 == 0)
        for col_idx, val in enumerate(row_data, 1):
            c = ws.cell(row=r_idx, column=col_idx)
            c.value = val
            c.font = Font(name="Calibri", size=9)
            if use_alt:
                c.fill = row_alt_fill
            c.border = thin_border
            if isinstance(val, (int, float)):
                c.alignment = Alignment(horizontal="right", vertical="center")
                c.number_format = "#,##0.00"
            else:
                c.alignment = Alignment(horizontal="left", vertical="center")

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            # Skip title merged rows for width calculation
            if cell.row in [1, 2, 3]:
                continue
            if cell.value:
                max_len = max(max_len, len(str(cell.value)))
        ws.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 40)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
